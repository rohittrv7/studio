import 'dart:io' show Platform;

import 'package:firebase_messaging/firebase_messaging.dart';
import 'package:flutter/foundation.dart' show kIsWeb;
import 'package:flutter/material.dart';
import 'package:hive_flutter/hive_flutter.dart';

// ---------------------------------------------------------------------------
// Background message handler
// ---------------------------------------------------------------------------
//
// Must be a top-level function (not a class method) so that Flutter can call
// it inside an Android background isolate.  The `@pragma` annotation prevents
// tree-shaking from stripping it in release builds.
@pragma('vm:entry-point')
Future<void> _firebaseMessagingBackgroundHandler(RemoteMessage message) async {
  // Background handling is intentionally lightweight — the app is not in
  // memory.  We simply ignore the message here; the user will see the system
  // notification generated by FCM, and tapping it will be handled by
  // FirebaseMessaging.onMessageOpenedApp or getInitialMessage when the app
  // resumes/launches.
  debugPrint(
    '[NotificationService] Background message received: '
    'messageId=${message.messageId}, data=${message.data}',
  );
}

// ---------------------------------------------------------------------------
// Hive key for first-launch permission flag
// ---------------------------------------------------------------------------
const String _kPermissionAskedKey = 'notificationPermissionAsked';

// ---------------------------------------------------------------------------
// NotificationService
// ---------------------------------------------------------------------------

/// Centralises all Firebase Cloud Messaging setup and handling for the app.
///
/// Responsibilities:
/// - Request notification permissions on first launch.
/// - Retrieve the FCM device token and return it for backend registration.
/// - Handle **foreground** messages via an in-app [SnackBar] banner.
/// - Handle **background tap** (app in background → user taps notification):
///   extract `galleryId` and navigate to `/galleries/{galleryId}`.
/// - Handle **terminated state** (app was closed → notification tap launches
///   app): same extraction + navigation.
/// - Configure the `gallery_ready` Android notification channel.
///
/// Usage:
/// ```dart
/// await NotificationService.initialize(navigatorKey);
/// ```
class NotificationService {
  NotificationService._(); // Prevent instantiation — all methods are static.

  // ---------------------------------------------------------------------------
  // Initialise — must be called after Firebase.initializeApp()
  // ---------------------------------------------------------------------------

  /// Sets up all FCM listeners and configures the Android notification channel.
  ///
  /// [navigatorKey] is used to push navigation commands from outside the
  /// widget tree (background tap / terminated-state handlers).
  static Future<void> initialize(GlobalKey<NavigatorState> navigatorKey) async {
    // Register the background message handler.
    FirebaseMessaging.onBackgroundMessage(_firebaseMessagingBackgroundHandler);

    // Configure the Android high-priority notification channel.
    await _configureAndroidChannel();

    // Foreground message banner.
    FirebaseMessaging.onMessage.listen((RemoteMessage message) {
      _showForegroundBanner(navigatorKey, message);
    });

    // Background tap: app was in background, user tapped the notification.
    FirebaseMessaging.onMessageOpenedApp.listen((RemoteMessage message) {
      _handleNavigationMessage(navigatorKey, message);
    });

    // Terminated state: app was closed, user tapped the notification.
    final initialMessage =
        await FirebaseMessaging.instance.getInitialMessage();
    if (initialMessage != null) {
      // Delay navigation until the first frame so the widget tree is ready.
      WidgetsBinding.instance.addPostFrameCallback((_) {
        _handleNavigationMessage(navigatorKey, initialMessage);
      });
    }
  }

  // ---------------------------------------------------------------------------
  // Permission + token retrieval
  // ---------------------------------------------------------------------------

  /// Requests notification permission (if not yet asked) and returns the FCM
  /// device token, or `null` if permission was denied or the token is
  /// unavailable.
  ///
  /// Stores a flag in Hive so the system permission dialog is shown only once.
  static Future<String?> requestPermissionAndGetToken() async {
    // Check whether we have already asked on a previous launch.
    final alreadyAsked = _getPermissionAskedFlag();

    if (!alreadyAsked) {
      await _setPermissionAskedFlag();
      final settings = await FirebaseMessaging.instance.requestPermission(
        alert: true,
        badge: true,
        sound: true,
        announcement: false,
        carPlay: false,
        criticalAlert: false,
        provisional: false,
      );

      debugPrint(
        '[NotificationService] Permission status: '
        '${settings.authorizationStatus}',
      );

      if (settings.authorizationStatus == AuthorizationStatus.denied) {
        return null;
      }
    } else {
      // Already asked — check the current authorisation status.
      final settings =
          await FirebaseMessaging.instance.getNotificationSettings();
      if (settings.authorizationStatus == AuthorizationStatus.denied) {
        return null;
      }
    }

    // Android 13+ requires explicit POST_NOTIFICATIONS permission; the
    // FirebaseMessaging.requestPermission call above covers it.
    try {
      final token = await FirebaseMessaging.instance.getToken();
      debugPrint(
        '[NotificationService] FCM token: '
        '${token != null ? '${token.substring(0, 12)}...' : 'null'}',
      );
      return token;
    } catch (e) {
      debugPrint('[NotificationService] Failed to get FCM token: $e');
      return null;
    }
  }

  // ---------------------------------------------------------------------------
  // Private helpers
  // ---------------------------------------------------------------------------

  /// Configures the `gallery_ready` Android notification channel.
  ///
  /// On Android 8+ (API 26+) notifications require a channel.  We declare the
  /// channel in code in addition to the AndroidManifest meta-data so that the
  /// channel properties (name, description, importance) are applied
  /// programmatically at runtime.
  static Future<void> _configureAndroidChannel() async {
    if (kIsWeb || !Platform.isAndroid) return;

    // Tell FCM which channel to use for data messages on Android.
    await FirebaseMessaging.instance
        .setForegroundNotificationPresentationOptions(
      alert: true,
      badge: true,
      sound: true,
    );
  }

  /// Extracts `galleryId` from [message] and navigates to `/galleries/:id`.
  ///
  /// Gracefully no-ops if the `galleryId` is absent or the navigator is not
  /// ready.
  static void _handleNavigationMessage(
    GlobalKey<NavigatorState> navigatorKey,
    RemoteMessage message,
  ) {
    final galleryId = message.data['galleryId'] as String?;
    if (galleryId == null || galleryId.isEmpty) {
      debugPrint(
        '[NotificationService] Notification tapped but galleryId is missing '
        'from data payload: ${message.data}',
      );
      return;
    }

    final context = navigatorKey.currentContext;
    if (context == null) {
      debugPrint(
        '[NotificationService] Navigator context is not available yet.',
      );
      return;
    }

    debugPrint(
      '[NotificationService] Navigating to gallery: $galleryId',
    );

    // Use Navigator directly so this module has no dependency on GoRouter.
    // The push is done on the root navigator so it works from any route.
    navigatorKey.currentState?.pushNamedAndRemoveUntil(
      '/galleries/$galleryId',
      (route) => route.isFirst,
    );
  }

  /// Shows an in-app [SnackBar] banner for foreground messages.
  static void _showForegroundBanner(
    GlobalKey<NavigatorState> navigatorKey,
    RemoteMessage message,
  ) {
    final notification = message.notification;
    if (notification == null) return;

    final context = navigatorKey.currentContext;
    if (context == null) return;

    final title = notification.title ?? 'New notification';
    final body = notification.body ?? '';
    final galleryId = message.data['galleryId'] as String?;

    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              title,
              style: const TextStyle(fontWeight: FontWeight.bold),
            ),
            if (body.isNotEmpty)
              Text(
                body,
                maxLines: 2,
                overflow: TextOverflow.ellipsis,
              ),
          ],
        ),
        duration: const Duration(seconds: 4),
        action: galleryId != null
            ? SnackBarAction(
                label: 'View',
                onPressed: () {
                  _handleNavigationMessage(navigatorKey, message);
                },
              )
            : null,
        behavior: SnackBarBehavior.floating,
      ),
    );
  }

  // ---------------------------------------------------------------------------
  // Hive flag helpers
  // ---------------------------------------------------------------------------

  static bool _getPermissionAskedFlag() {
    try {
      // authBox is opened during HiveStorage.init(); read the flag from it.
      final box = Hive.box<dynamic>('authBox');
      return box.get(_kPermissionAskedKey, defaultValue: false) as bool;
    } catch (_) {
      return false;
    }
  }

  static Future<void> _setPermissionAskedFlag() async {
    try {
      final box = Hive.box<dynamic>('authBox');
      await box.put(_kPermissionAskedKey, true);
    } catch (_) {
      // Non-fatal — the permission dialog may appear again on next launch.
    }
  }
}
